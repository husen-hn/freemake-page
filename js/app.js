function applyTranslations(language) {
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = getTranslation(language, element.dataset.i18n);

    if (typeof value === "string") {
      element.textContent = value;
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = getTranslation(language, element.dataset.i18nAlt);

    if (typeof value === "string") {
      element.alt = value;
    }
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = getTranslation(language, element.dataset.i18nAria);

    if (typeof value === "string") {
      element.setAttribute("aria-label", value);
    }
  });
}

function applyLanguage(language) {
  const normalizedLanguage = language === "fa" ? "fa" : "en";

  root.lang = normalizedLanguage;

  root.dir = normalizedLanguage === "fa" ? "rtl" : "ltr";

  applyTranslations(normalizedLanguage);

  const languageLabel = document.getElementById("language-label");

  if (languageLabel) {
    languageLabel.textContent = normalizedLanguage === "en" ? "فا" : "EN";
  }

  document.title =
    normalizedLanguage === "fa"
      ? "فری‌میک — تبدیل‌کننده ویدیو و صوت"
      : document.querySelector("title")?.textContent || "Freemake";

  localStorage.setItem("freemake-language", normalizedLanguage);
}

function applyTheme(theme) {
  const normalizedTheme = theme === "dark" ? "dark" : "light";

  root.dataset.theme = normalizedTheme;

  const themeIcon = document.querySelector(".theme-icon");

  if (themeIcon) {
    themeIcon.textContent = normalizedTheme === "dark" ? "☀" : "☾";
  }

  localStorage.setItem("freemake-theme", normalizedTheme);
}

function setupThemeToggle() {
  const button = document.getElementById("theme-toggle");

  if (!button) return;

  button.addEventListener("click", () => {
    applyTheme(root.dataset.theme === "dark" ? "light" : "dark");
  });
}

function setupLanguageToggle() {
  const button = document.getElementById("language-toggle");

  if (!button) return;

  button.addEventListener("click", () => {
    applyLanguage(root.lang === "fa" ? "en" : "fa");
  });
}

function setupMobileMenu() {
  const menuButton = document.getElementById("menu-button");

  const closeButton = document.getElementById("close-menu");

  const menu = document.getElementById("mobile-menu");

  const overlay = document.getElementById("mobile-overlay");

  if (!menuButton || !closeButton || !menu || !overlay) {
    return;
  }

  function openMenu() {
    menu.classList.add("open");
    overlay.classList.add("open");

    menuButton.setAttribute("aria-expanded", "true");

    document.body.style.overflow = "hidden";
  }

  function closeMenu() {
    menu.classList.remove("open");
    overlay.classList.remove("open");

    menuButton.setAttribute("aria-expanded", "false");

    document.body.style.overflow = "";
  }

  menuButton.addEventListener("click", openMenu);

  closeButton.addEventListener("click", closeMenu);

  overlay.addEventListener("click", closeMenu);

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      closeMenu();
    }
  });
}

